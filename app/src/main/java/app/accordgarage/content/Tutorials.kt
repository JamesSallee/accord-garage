enum class Safety(val label: String) {
    GREEN("DIY"),
    AMBER("WITH CARE"),
    RED("PRO ONLY"),
}

data class VideoLink(val label: String, val url: String)

data class Step(
    val title: String,
    val body: String,
    val substeps: List<String> = emptyList(),
    val checks: List<String> = emptyList(),
    val videos: List<VideoLink> = emptyList(),
    /** A manual search the step offers, for a spec the owner's manual holds. */
    val manualQuery: String? = null,
    val caution: String? = null,
)

data class Tutorial(
    val id: String,
    val title: String,
    val system: CarSystem,
    val jobIds: List<String>,
    val difficulty: Int,
    val minutes: Int,
    val safety: Safety,
    val summary: String,
    val tools: List<String>,
    val parts: List<String>,
    val steps: List<Step>,
    val references: List<VideoLink> = emptyList(),
)

